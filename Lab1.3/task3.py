# Пользователь вводит два числа. Одно присваивается одной переменной, 
# а второе — другой. Необходимо поменять значения переменных так, чтобы
# значение первой оказалось во второй, а второй — в первой

a = int(input("Введите число a: "))
b = int(input("Введите число b: "))

a, b = b, a

print(f"a = {a}; b = {b}")